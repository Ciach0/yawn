use crate::error::CliError;
use std::fs;
use std::path::{Path, PathBuf};

const MAIN_RSX: &str = r#"// The entry point: the component named `App` is what the browser mounts. Everything outside a
// component is plain Rust, so `use` and `mod helpers;` work as in any crate root.

component App() {
    let count = signal(0);

    view {
        <main>
            <h1>"Hello from Yawn"</h1>
            <button on:click={move || count.update(|n| *n += 1)}>"clicked {count} times"</button>
        </main>
    }

    style {
        main { font-family: system-ui, sans-serif; max-width: 32rem; margin: 4rem auto; padding: 0 1rem; }
        button { font: inherit; padding: 0.4rem 0.9rem; cursor: pointer; }
    }
}
"#;

const GITIGNORE: &str = "/target\n# generated by `yawn dev` / `yawn rsx`\n/.yawn\n";

fn valid_name(name: &str) -> Result<(), CliError> {
    let ok = !name.is_empty()
        && !name.starts_with(|c: char| c.is_ascii_digit() || c == '-')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if ok {
        Ok(())
    } else {
        Err(CliError::new(format!("`{name}` is not a valid project name"))
            .hint("use letters, digits, `-` and `_`, starting with a letter"))
    }
}

fn cargo_toml(name: &str, yawn_path: Option<&Path>) -> String {
    let dep = match yawn_path {
        Some(p) => {
            format!("yawn-web = {{ path = \"{}\" }}", p.display().to_string().replace('\\', "/"))
        }
        None => format!("yawn-web = \"{}\"", env!("CARGO_PKG_VERSION")),
    };
    format!(
        "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n\
         [dependencies]\n{dep}\n\n\
         # Standalone project: not a member of any enclosing workspace.\n[workspace]\n\n\
         [profile.dev]\n# A small wasm links and loads faster, which is most of the save-to-reload time.\ndebug = false\nopt-level = \"s\"\n"
    )
}

fn yawn_toml(name: &str, tailwind: bool) -> String {
    let mut s = format!(
        "[app]\ntitle = \"{name}\"\n\n# Port: `yawn dev --port N` > $PORT > this value > 3000.\n# [server]\n# port = 3000\n"
    );
    if tailwind {
        s.push_str("\n# Tailwind CSS: built by `yawn dev` from the classes used in src/, class completion in the editor.\n[tailwind]\nenabled = true\n");
    }
    s
}

/// Creates the project in `dir` (which must be missing or empty) and returns its path
pub fn create(dir: &Path, yawn_path: Option<&Path>, tailwind: bool) -> Result<PathBuf, CliError> {
    let name = dir
        .file_name()
        .and_then(|n| n.to_str())
        .ok_or_else(|| CliError::new("cannot derive a project name from the path"))?;
    valid_name(name)?;
    if dir.exists() && (!dir.is_dir() || fs::read_dir(dir)?.next().is_some()) {
        return Err(CliError::new(format!(
            "`{}` exists and is not an empty directory",
            dir.display()
        )));
    }
    let yawn_path = yawn_path
        .map(fs::canonicalize)
        .transpose()
        .map_err(|e| CliError::new(format!("--yawn-path: {e}")))?;
    fs::create_dir_all(dir.join("src"))?;
    fs::write(dir.join("Cargo.toml"), cargo_toml(name, yawn_path.as_deref()))?;
    fs::write(dir.join("Yawn.toml"), yawn_toml(name, tailwind))?;
    fs::write(dir.join(".gitignore"), GITIGNORE)?;
    fs::write(dir.join("src/main.rsx"), MAIN_RSX)?;
    Ok(dir.to_path_buf())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("yawn-cli-new-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&d);
        d
    }

    #[test]
    fn creates_a_project_that_compiles_to_rust() {
        let dir = temp("ok").join("hello-app");
        create(&dir, None, false).unwrap();
        let cargo = fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(
            cargo.contains("name = \"hello-app\"")
                && !cargo.contains("[lib]")
                && !cargo.contains("[[bin]]"),
            "{cargo}"
        );
        crate::dev::rsx::compile(&dir).unwrap();
        assert!(
            dir.join(".yawn/client.rs").exists()
                && dir.join(".yawn/server.rs").exists()
                && !dir.join("src/lib.rs").exists()
        );
        let _ = fs::remove_dir_all(dir.parent().unwrap());
    }

    #[test]
    fn refuses_bad_names_and_non_empty_directories() {
        assert!(create(&temp("bad").join("1abc"), None, false).is_err());
        assert!(create(&temp("bad2").join("a b"), None, false).is_err());
        let dir = temp("full").join("app");
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("keep.txt"), "x").unwrap();
        assert!(create(&dir, None, false).is_err());
        assert_eq!(fs::read_to_string(dir.join("keep.txt")).unwrap(), "x");
        let _ = fs::remove_dir_all(dir.parent().unwrap());
    }

    #[test]
    fn tailwind_flag_enables_the_section() {
        let dir = temp("tw");
        create(&dir, None, true).unwrap();
        let cfg = yawn::config::ProjectConfig::load(&dir).unwrap().unwrap();
        assert!(cfg.tailwind.enabled);
        let plain = temp("tw-off");
        create(&plain, None, false).unwrap();
        assert!(!yawn::config::ProjectConfig::load(&plain).unwrap().unwrap().tailwind.enabled);
    }

    #[test]
    fn path_dependency_is_absolute() {
        let root = temp("path");
        let dir = root.join("p");
        fs::create_dir_all(&root).unwrap();
        create(&dir, Some(&root), false).unwrap();
        let cargo = fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(cargo.contains("yawn-web = { path = \"/"), "{cargo}");
        let _ = fs::remove_dir_all(&root);
    }
}
